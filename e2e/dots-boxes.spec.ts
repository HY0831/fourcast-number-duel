import {test,expect,type Page} from '@playwright/test'
import {boxEdges,edgeCount} from '../client/src/games/dots-boxes/dots-engine.mjs'
const edges=(page:Page)=>page.locator('.db-edge')
const draw=async(page:Page,index:number)=>{
  await edges(page).nth(index).focus()
  await page.keyboard.press('Enter')
}
async function local(page:Page,size:3|5|7=3){
  await page.goto('/games/dots-boxes')
  await page.getByRole('group',{name:'Choose play mode'}).getByRole('button',{name:'Same device'}).click()
  await page.getByRole('group',{name:'Board size'}).getByRole('button',{name:new RegExp('^'+size+'×'+size)}).click()
  await page.getByRole('button',{name:'Start local game'}).click()
  await expect(page.getByRole('heading',{name:'Dots & Boxes.'})).toBeVisible()
}
async function online(host:Page,guest:Page,size:3|5|7=3){
  await host.goto('/games/dots-boxes')
  await host.getByLabel('YOUR NICKNAME').fill('Alex')
  await host.getByRole('group',{name:'Board size'}).getByRole('button',{name:new RegExp('^'+size+'×'+size)}).click()
  const create=host.getByRole('button',{name:'Create Dots & Boxes room'})
  await expect(create).toBeEnabled()
  await create.click()
  await expect(host.getByRole('heading',{name:'Invite your friend.'})).toBeVisible()
  const code=(await host.locator('.db-invite span').allTextContents()).join('')
  expect(code).toMatch(/^[A-Z0-9]{6}$/)
  await guest.goto('/games/dots-boxes?room='+code)
  await guest.getByLabel('YOUR NICKNAME').fill('Blair')
  await guest.getByRole('button',{name:'Join room'}).click()
  const join=guest.getByRole('button',{name:'Join Dots & Boxes room'})
  await expect(join).toBeEnabled()
  await join.click()
  await expect(host.getByText('Your turn — draw a line!')).toBeVisible()
  await expect(guest.getByText('Alex is playing')).toBeVisible()
  return code
}
