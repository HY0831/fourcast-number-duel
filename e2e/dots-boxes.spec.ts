test('local game remains playable if browser storage is inaccessible',async({page})=>{
  await page.addInitScript(()=>{
    Object.defineProperty(window,'localStorage',{configurable:true,get(){throw new DOMException('Access denied','SecurityError')}})
  })
  await local(page)
  await draw(page,0)
  await expect(edges(page).nth(0)).toHaveAttribute('aria-label',/drawn by Blue/)
})
