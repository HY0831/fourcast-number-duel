test('all three board sizes display correct dots, lines and touch targets without mobile overflow',async({page})=>{
  for(const [size,width] of [[3,320],[5,390],[7,768]] as const){
    await page.setViewportSize({width,height:800})
    await local(page,size)
    await expect(edges(page)).toHaveCount(edgeCount(size))
    await expect(page.locator('.db-board circle')).toHaveCount((size+1)*(size+1))
    expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),'overflow at '+width).toBe(false)
  }
})
test('completing a square claims it and grants an extra turn; history review is read-only',async({page})=>{
  await local(page)
  const [top,bottom,left,right]=boxEdges(3,0,0)
  for(const index of [top,bottom,left,right])await draw(page,index)
  await expect(page.getByText("Player 2's turn · Coral · Box claimed — play again!")).toBeVisible()
  await expect(page.locator('.db-score-row').nth(1).locator('b')).toHaveText('1')
  await expect(page.locator('.db-board text')).toHaveText(['C'])
  await page.getByRole('button',{name:'Starting board'}).click()
  await expect(page.getByText(/Reviewing starting board/)).toBeVisible()
  await expect(page.locator('.db-board text')).toHaveCount(0)
  await expect(edges(page).nth(top)).toHaveAttribute('aria-disabled','true')
  await page.getByRole('button',{name:'Live board'}).click()
  await expect(page.locator('.db-board text')).toHaveText(['C'])
  await draw(page,top+1)
  await expect(page.getByText("Player 1's turn · Blue")).toBeVisible()
})
test('local game saves on reload, plays offline and swaps first player on rematch',async({page})=>{
  await local(page)
  await draw(page,0)
  await page.context().setOffline(true)
  await draw(page,1)
  await expect(page.getByText("Player 1's turn · Blue")).toBeVisible()
  await page.context().setOffline(false)
  await page.reload()
  await expect(page.getByRole('button',{name:'Resume saved local game'})).toBeVisible()
  await page.getByRole('button',{name:'Resume saved local game'}).click()
  await expect(edges(page).nth(0)).toHaveAttribute('aria-label',/drawn by Blue/)
  await expect(edges(page).nth(1)).toHaveAttribute('aria-label',/drawn by Coral/)
  page.once('dialog',d=>d.accept())
  await page.getByRole('button',{name:'Resign round'}).click()
  await expect(page.getByText('Player 2 wins!')).toBeVisible()
  await page.getByRole('button',{name:'Play rematch'}).click()
  await expect(page.getByText("Player 2's turn · Coral")).toBeVisible()
  await expect(page.getByText('LOCAL TWO-PLAYER · ROUND 2')).toBeVisible()
})
test('three-by-three local game finishes after all 24 valid edges',async({page})=>{
  await local(page)
  for(let index=0;index<edgeCount(3);index++)await draw(page,index)
  await expect(page.getByText(/wins!/)).toBeVisible()
  await expect(page.getByText('9 of 9 boxes captured')).toBeVisible()
  await expect(page.getByRole('button',{name:'Play rematch'})).toBeVisible()
  await expect(page.locator('.db-board text')).toHaveCount(9)
})
test('online two-device private room supports extra turns, reconnect and consensual rematch',async({page,browser})=>{
  test.setTimeout(90_000)
  const ctx=await browser.newContext(),guest=await ctx.newPage()
  try{
    await online(page,guest,3)
    await expect(edges(page)).toHaveCount(24)
    const sequence=boxEdges(3,0,0)
    for(const index of sequence){
      const hostTurn=await page.getByText('Your turn — draw a line!').isVisible()
      await draw(hostTurn?page:guest,index)
    }
    await expect(page.locator('.db-score-row').nth(1).locator('b')).toHaveText('1')
    await expect(guest.getByText('Your turn — draw a line!')).toBeVisible()
    await guest.reload()
    await expect(guest.getByText('Your turn — draw a line!')).toBeVisible()
    await expect(guest.locator('.db-history-items button')).toHaveCount(5)
    guest.once('dialog',d=>d.accept())
    await guest.getByRole('button',{name:'Resign round'}).click()
    await expect(page.getByText('Alex wins!')).toBeVisible()
    await expect(guest.getByText('Alex wins!')).toBeVisible()
    await page.getByRole('button',{name:'Request rematch'}).click()
    await guest.getByRole('button',{name:'Request rematch'}).click()
    await expect(guest.getByText('Your turn — draw a line!')).toBeVisible()
    await expect(page.getByText('Blair is playing')).toBeVisible()
    await expect(page.getByText('ROOM')).toHaveCount(0)
    await expect(page.locator('.db-score-row').first().locator('b')).toHaveText('0')
  }finally{await ctx.close()}
})
