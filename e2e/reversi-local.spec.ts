import {test,expect,type Page} from '@playwright/test'
async function startLocal(page:Page){
 await page.goto('/games/reversi')
 await page.getByRole('button',{name:/Play local two-player/}).click()
 await expect(page.getByText('TWO PLAYERS · ONE SCREEN')).toBeVisible()
 await page.getByRole('button',{name:'Start local match'}).click()
 await expect(page.getByRole('heading',{name:'The battle is on.'})).toBeVisible()
}
const cells=(page:Page)=>page.locator('.rv-board .rv-cell')
test('same-device mode works offline with two players and a complete 8x8 opening',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await startLocal(page)
 await expect(cells(page)).toHaveCount(64)
 await expect(page.locator('.rv-cell-legal')).toHaveCount(4)
 await expect(page.getByText("Player 1's turn — Black!")).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
 await page.context().setOffline(true)
 await page.getByRole('gridcell',{name:/Row 3, column 4: Empty, legal move/}).click()
 await expect(page.getByText("Player 2's turn — White!")).toBeVisible()
 await expect(page.locator('.rv-score').first().locator('b')).toHaveText('4')
 await expect(page.locator('.rv-score').nth(1).locator('b')).toHaveText('1')
 await expect(page.getByText('1. Black · d6 · 1 flipped')).toBeVisible()
 await page.context().setOffline(false)
})
test('move review shows snapshots without changing live state or legal turn',async({page})=>{
 await startLocal(page)
 await page.getByRole('gridcell',{name:/Row 3, column 4: Empty, legal move/}).click()
 await page.getByRole('button',{name:'Start · 2–2'}).click()
 await expect(page.getByText('Viewing the starting board')).toBeVisible()
 await expect(page.locator('.rv-cell-legal')).toHaveCount(0)
 await expect(cells(page).nth(19)).toHaveAttribute('aria-label',/Empty/)
 await page.getByRole('button',{name:/1. Black · d6/}).click()
 await expect(cells(page).nth(19)).toHaveAttribute('aria-label',/Black, last move/)
 await page.getByRole('button',{name:'Live board'}).click()
 await expect(page.getByText("Player 2's turn — White!")).toBeVisible()
 await expect(page.locator('.rv-cell-legal')).toHaveCount(3)
})
test('same-device progress resumes across reloads; resignation awards opponent and rematches swap colours',async({page})=>{
 await startLocal(page)
 await page.getByRole('gridcell',{name:/Row 3, column 4: Empty, legal move/}).click()
 await page.reload()
 await expect(page.getByRole('button',{name:'Resume saved local match'})).toBeVisible()
 await page.getByRole('button',{name:'Resume saved local match'}).click()
 await expect(cells(page).nth(19)).toHaveAttribute('aria-label',/Black, last move/)
 page.once('dialog',dialog=>dialog.accept())
 await page.getByRole('button',{name:'Resign round'}).click()
 await expect(page.getByText('Player 1 wins!')).toBeVisible()
 await page.reload()
 await page.getByRole('button',{name:'Resume saved local match'}).click()
 await expect(page.getByText('Player 1 wins!')).toBeVisible()
 await page.getByRole('button',{name:'Play another round'}).click()
 await expect(page.getByText("Player 2's turn — Black!")).toBeVisible()
 await expect(page.locator('.rv-cell-legal')).toHaveCount(4)
 await expect(page.getByText('LOCAL TWO-PLAYER · ROUND 2')).toBeVisible()
})
test('local mode allows custom names, keeps progress when returning to mode menu and survives 320px',async({page})=>{
 await page.setViewportSize({width:320,height:740})
 await page.goto('/games/reversi')
 await page.getByRole('button',{name:/Play local two-player/}).click()
 await page.getByLabel('Player 1').fill('Alice')
 await page.getByLabel('Player 2').fill('Bea')
 await page.getByRole('button',{name:'Start local match'}).click()
 await expect(page.getByText("Alice's turn — Black!")).toBeVisible()
 await page.locator('.rv-cell-legal').first().click()
 await page.getByRole('button',{name:'Mode menu'}).click()
 await expect(page.getByRole('button',{name:'Resume saved local match'})).toBeVisible()
 await page.getByRole('button',{name:'Resume saved local match'}).click()
 await expect(page.getByText("Bea's turn — White!")).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
})
test('online resignation requires confirmation and both players see the immutable move history',async({page,browser})=>{
 test.setTimeout(120_000)
 const context=await browser.newContext(),guest=await context.newPage()
 try{
  await page.goto('/games/reversi')
  await page.getByLabel('YOUR NICKNAME').fill('Alex')
  await page.getByRole('button',{name:'Create Reversi room'}).click()
  const code=(await page.locator('.rv-invite span').allTextContents()).join('')
  await guest.goto('/games/reversi?room='+code)
  await guest.getByLabel('YOUR NICKNAME').fill('Blair')
  await guest.getByRole('button',{name:'Join Reversi room'}).click()
  await page.getByRole('gridcell',{name:/Row 3, column 4: Empty, legal move/}).click()
  await expect(guest.getByRole('button',{name:/1. Black · d6/})).toBeVisible()
  await guest.getByRole('button',{name:'Start · 2–2'}).click()
  await expect(guest.locator('.rv-cell-legal')).toHaveCount(0)
  await guest.getByRole('button',{name:'Live board'}).click()
  guest.once('dialog',d=>d.dismiss())
  await guest.getByRole('button',{name:'Resign round'}).click()
  await expect(guest.getByText('Your turn — place a disc!')).toBeVisible()
  guest.once('dialog',d=>d.accept())
  await guest.getByRole('button',{name:'Resign round'}).click()
  await expect(page.getByRole('heading',{name:'Round complete.'})).toBeVisible()
  await expect(page.getByText('You win the board!')).toBeVisible()
  await expect(guest.getByText('Alex wins!')).toBeVisible()
  await page.getByRole('button',{name:'Request rematch'}).click()
  await guest.getByRole('button',{name:'Request rematch'}).click()
  await expect(page.getByText('Blair is thinking')).toBeVisible()
  await expect(guest.getByText('Your turn — place a disc!')).toBeVisible()
  await expect(page.getByRole('button',{name:'Start · 2–2'})).toBeVisible()
 }finally{await context.close()}
})
