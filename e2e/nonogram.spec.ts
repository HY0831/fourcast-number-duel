import { expect, test, type Page } from '@playwright/test'

const SAVED = 'playgrove:nonogram:v1:'
const board = (page: Page) => page.locator('.ng-board-grid')
const cell = (page: Page, row: number, col: number) => page.getByRole('gridcell', {name:new RegExp(`^Row ${row}, column ${col}:`)})

async function playHeart(page: Page) {
  await page.goto('/games/nonogram')
  await page.getByRole('button',{name:'Play Heart'}).click()
  await expect(page.getByRole('heading',{name:'Heart.'})).toBeVisible()
}

test('Playgrove lists nine games and Nonogram opens a 30-picture gallery without spoiling artwork', async ({page}) => {
  await page.setViewportSize({width:390,height:844})
  await page.goto('/')
  await expect(page.getByText('09 GAMES AVAILABLE')).toBeVisible()
  for(const name of ['Fourcast','Sudoku','Bingo Duel','Minesweeper','Connect Four','2048','Nonogram','Hashi: Bridges','Reversi'])
    await expect(page.getByRole('heading',{name,exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Play Nonogram'}).click()
  await expect(page).toHaveURL(/\/games\/nonogram$/)
  await expect(page.getByRole('heading',{name:'Nonogram.'})).toBeVisible()
  await expect(page.locator('.ng-puzzle-card')).toHaveCount(30)
  await expect(page.locator('.ng-card-art .ng-artwork')).toHaveCount(0)
  await expect(page.locator('.ng-card-art .ng-mystery')).toHaveCount(30)
  await page.getByRole('button',{name:'All games'}).click()
  await expect(page).toHaveURL(/\/$/)
})

test('library difficulties expose exactly ten specific authored pictures; category and search filters work', async ({page}) => {
  await page.goto('/games/nonogram')
  for(const [difficulty,size] of [['Easy','5'],['Medium','10'],['Hard','15']]) {
    await page.getByRole('group',{name:'Difficulty filter'}).getByRole('button',{name:difficulty}).click()
    await expect(page.locator('.ng-puzzle-card')).toHaveCount(10)
    await expect(page.locator('.ng-card-level').first()).toContainText(size+'×'+size)
  }
  await page.getByRole('group',{name:'Difficulty filter'}).getByRole('button',{name:'All'}).click()
  await page.getByRole('group',{name:'Picture category filter'}).getByRole('button',{name:'Animals'}).click()
  await expect(page.locator('.ng-puzzle-card')).toHaveCount(8)
  await page.getByRole('group',{name:'Picture category filter'}).getByRole('button',{name:'All'}).click()
  await page.getByRole('textbox',{name:'Search pictures'}).fill('cat')
  await expect(page.locator('.ng-puzzle-card')).toHaveCount(2)
  await expect(page.getByRole('heading',{name:'Cat Face'})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Sitting Cat'})).toBeVisible()
  await page.getByRole('textbox',{name:'Search pictures'}).fill('unlisted photo')
  await expect(page.getByText('No pictures match those filters.')).toBeVisible()
  await page.getByRole('button',{name:'Clear filters'}).click()
  await expect(page.locator('.ng-puzzle-card')).toHaveCount(30)
})

test('5x5 clue board supports fill, toggle, X mode, right-click and undo',async ({page}) => {
  await playHeart(page)
  await expect(page.getByRole('gridcell')).toHaveCount(25)
  await expect(page.locator('.ng-col-clue')).toHaveCount(5)
  await expect(page.locator('.ng-row-clue')).toHaveCount(5)
  await expect(page.getByLabel('Row 1 clues: 1 1')).toBeVisible()
  await expect(page.getByLabel('Column 2 clues: 4')).toBeVisible()
  await cell(page,1,2).click()
  await expect(cell(page,1,2)).toHaveAttribute('aria-label', /^Row 1, column 2: filled\. Row clues: /)
  await cell(page,1,2).click()
  await expect(cell(page,1,2)).toHaveAttribute('aria-label', /^Row 1, column 2: empty\. Row clues: /)
  await page.getByRole('group',{name:'Board marking mode'}).getByRole('button',{name:'Mark X'}).click()
  await cell(page,1,1).click()
  await expect(cell(page,1,1)).toHaveAttribute('aria-label', /^Row 1, column 1: X mark\. Row clues: /)
  await page.getByRole('button',{name:'Undo'}).click()
  await expect(cell(page,1,1)).toHaveAttribute('aria-label', /^Row 1, column 1: empty\. Row clues: /)
  await cell(page,1,1).click({button:'right'})
  await expect(cell(page,1,1)).toHaveAttribute('aria-label', /^Row 1, column 1: X mark\. Row clues: /)
  await cell(page,1,2).focus()
  await page.keyboard.press('f')
  await expect(cell(page,1,2)).toHaveAttribute('aria-label', /^Row 1, column 2: filled\. Row clues: /)
  await page.keyboard.press('ArrowRight')
  await expect(cell(page,1,3)).toBeFocused()
})

test('hints, undo, pause, restart confirmation and browser progress restoration',async ({page})=>{
  await playHeart(page)
  await cell(page,1,2).click()
  await page.getByRole('button',{name:'Pause'}).click()
  await expect(page.getByText('Puzzle paused — resume to keep solving.')).toBeVisible()
  await expect(cell(page,1,2)).toBeDisabled()
  await page.getByRole('button',{name:'Resume'}).click()
  await page.getByRole('button',{name:/Hint \(3 left\)/}).click()
  await expect(page.getByRole('button',{name:/Hint \(2 left\)/})).toBeVisible()
  await page.getByRole('button',{name:'Undo'}).click()
  await expect(page.getByRole('button',{name:/Hint \(3 left\)/})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading',{name:'Heart.'})).toBeVisible()
  await expect(cell(page,1,2)).toHaveAttribute('aria-label', /^Row 1, column 2: filled\. Row clues: /)
  page.once('dialog',dialog=>dialog.dismiss())
  await page.getByRole('button',{name:'Restart'}).click()
  await expect(cell(page,1,2)).toHaveAttribute('aria-label', /^Row 1, column 2: filled\. Row clues: /)
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'Restart'}).click()
  await expect(cell(page,1,2)).toHaveAttribute('aria-label', /^Row 1, column 2: empty\. Row clues: /)
})

test('solving a fixed picture reveals its real pixel artwork and collection completion',async ({page})=>{
  await playHeart(page)
  const pattern=['01010','11111','11111','01110','00100']
  for(let row=0;row<5;row++)for(let col=0;col<5;col++)if(pattern[row][col]==='1')await cell(page,row+1,col+1).click()
  await expect(page.getByText('Picture unlocked!')).toBeVisible()
  await expect(page.locator('.ng-unlocked-art .ng-artwork')).toHaveCount(1)
  await expect(page.getByRole('gridcell').first()).toBeDisabled()
  await page.getByRole('button',{name:'Back to picture collection'}).click()
  await expect(page.getByText('1 / 30 completed')).toBeVisible()
  await expect(page.locator('.ng-card-complete .ng-artwork')).toHaveCount(1)
  await expect(page.getByRole('button',{name:'View / Replay Heart'})).toBeVisible()
  await page.reload()
  await expect(page.getByText('1 / 30 completed')).toBeVisible()
})

test('10x10 and 15x15 layouts keep clues aligned and do not overflow the whole mobile page',async ({page})=>{
  for(const width of [320,390,768,1440]){
    await page.setViewportSize({width,height:800})
    await page.goto('/games/nonogram')
    expect(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),`Gallery overflow at ${width}`).toBe(false)
    await page.getByRole('button',{name:'Play Sitting Cat'}).click()
    await expect(board(page)).toHaveAttribute('data-size','15')
    await expect(page.getByRole('gridcell')).toHaveCount(225)
    await expect(page.locator('.ng-col-clue')).toHaveCount(15)
    await expect(page.locator('.ng-row-clue')).toHaveCount(15)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),`Hard board page overflow at ${width}`).toBe(false)
    if(width<=390) {
      const sizes=await page.locator('.ng-board-holder').evaluate(e=>({scrollWidth:e.scrollWidth,clientWidth:e.clientWidth}))
      expect(sizes.scrollWidth).toBeGreaterThan(sizes.clientWidth)
    }
    await page.getByRole('button',{name:'Zoom in'}).click()
    await expect(board(page)).toHaveAttribute('data-zoom','large')
    await page.getByRole('button',{name:'Zoom out'}).click()
    await page.getByRole('button',{name:'Picture collection'}).click()
    await page.getByRole('button',{name:'Play Cat Face'}).click()
    await expect(board(page)).toHaveAttribute('data-size','10')
    await expect(page.getByRole('gridcell')).toHaveCount(100)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),`Medium board page overflow at ${width}`).toBe(false)
    await page.getByRole('button',{name:'Picture collection'}).click()
  }
})

test('invalid stored session is safely reset on return to the gallery puzzle',async ({page})=>{
  await page.goto('/games/nonogram')
  await page.evaluate(key=>localStorage.setItem(key,JSON.stringify({id:'E01',marks:[99,0],status:'completed'})),SAVED+'E01')
  await page.getByRole('button',{name:'Play Heart'}).click()
  await expect(cell(page,1,2)).toHaveAttribute('aria-label', /^Row 1, column 2: empty\. Row clues: /)
  await expect(page.getByRole('gridcell')).toHaveCount(25)
})
