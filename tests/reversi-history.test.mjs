import test from 'node:test';
import assert from 'node:assert/strict';
import {ReversiStore,BLACK,WHITE,startingBoard,publicReversiRoom} from '../server/reversi-engine.mjs';
test('server move history records each board snapshot without leaking player bearer tokens',()=>{
 const store=new ReversiStore(),{room,player:a}=store.create('Alex');
 a.socketId='host';
 const {player:b}=store.join(room.code,'Blair');
 b.socketId='guest';
 store.play(room.code,a.token,19);
 const snap=publicReversiRoom(room,b.id);
 assert.equal(snap.history.length,1);
 assert.equal(snap.history[0].disc,BLACK);
 assert.deepEqual(snap.history[0].flipped,[27]);
 assert.equal(snap.history[0].board[19],BLACK);
 assert.equal(snap.history[0].board[27],BLACK);
 assert.equal(snap.history[0].index,19);
 assert.equal(snap.moveCount,snap.history.length);
 assert.ok(!JSON.stringify(snap).includes(a.token));
 assert.ok(!JSON.stringify(snap).includes(b.token));
 const guestMove=snap.legalMoves[0];
 store.play(room.code,b.token,guestMove);
 const next=publicReversiRoom(room,a.id);
 assert.equal(next.history.length,2);
 assert.equal(next.history[0].board[guestMove],0,'historical snapshots are never mutated');
});
test('online resignation is authorized and awards a win, then consensual rematch resets history',()=>{
 const store=new ReversiStore(),{room,player:a}=store.create('Alex');a.socketId='host';
 const {player:b}=store.join(room.code,'Blair');b.socketId='guest';
 assert.throws(()=>store.resign(room.code,'bad token'),/do not belong/);
 assert.throws(()=>store.resign('MISSING',a.token),/not found/);
 store.play(room.code,a.token,19);
 store.resign(room.code,b.token);
 const ended=publicReversiRoom(room,a.id);
 assert.equal(ended.phase,'finished');
 assert.equal(ended.winnerId,a.id);
 assert.equal(ended.draw,false);
 assert.equal(ended.resignedBy,b.id);
 assert.equal(ended.history.length,1);
 assert.throws(()=>store.resign(room.code,a.token),/Only an active round/);
 store.requestRematch(room.code,a.token);
 store.requestRematch(room.code,b.token);
 const next=publicReversiRoom(room,b.id);
 assert.equal(next.round,2);
 assert.equal(next.resignedBy,null);
 assert.equal(next.history.length,0);
 assert.deepEqual(next.board,startingBoard());
 assert.equal(next.blackPlayerId,b.id);
 assert.deepEqual(next.legalMoves,[19,26,37,44]);
});
